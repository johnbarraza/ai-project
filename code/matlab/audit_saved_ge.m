function report = audit_saved_ge(input_root, output_json)
% Audit saved model results without solving GE or modifying the saved files.
files = dir(fullfile(input_root, '*', 'result.mat'));
assert(~isempty(files), 'No result.mat files found under the supplied folder.');
rows = cell(numel(files), 1);
for k = 1:numel(files)
    file_path = fullfile(files(k).folder, files(k).name);
    saved = load(file_path, 'result');
    x = saved.result;
    c = x.context;
    d = x.hjb_diagnostics;
    console = fileread(fullfile(files(k).folder, 'console.log'));
    tax = regexp(console, 'tau_c=([0-9.]+)', 'tokens', 'once');
    assert(c.ga == 1 && ~isempty(tax) && str2double(tax{1}) == 0, ...
        'Marginal value recovery requires log utility and zero consumption tax.');
    marginal_value = 1 ./ (d.cF + x.pI*d.cI);
    shape = value_shape_checks(x.a, x.V, marginal_value);
    mass = x.g * c.da;
    weight = @(v) sum(v .* mass, 'all');
    [~, case_id] = fileparts(files(k).folder);
    resource = x.YF-x.CF-c.d*x.KD-weight(c.kappa.*x.ellF) ...
        -weight(c.spread.*max(-x.a(:), 0));
    generator = x.generator;
    offdiag = generator-spdiags(diag(generator), 0, size(generator,1), size(generator,2));
    hjb_error = full(max(abs(c.rho*x.V(:)-d.u(:)-generator*x.V(:))));
    kfe_error = full(max(abs(generator'*x.g(:))));
    residuals = struct('capital', weight(x.a(:))-x.KD, ...
        'informal_good', x.CI-x.YI, 'formal_resources', resource, ...
        'government', x.T-c.tau*x.wF*x.LF, ...
        'hjb', hjb_error, 'kfe', kfe_error, ...
        'generator_row_sum', full(max(abs(sum(generator,2)))));
    checks = struct('finite_positive_total_expenditure', all(isfinite(marginal_value) & marginal_value > 0, 'all'), ...
        'mass', abs(sum(mass, 'all')-1) < 1e-8 && min(mass, [], 'all') > -1e-12, ...
        'generator', residuals.generator_row_sum < 1e-10 && all(nonzeros(offdiag) >= -1e-12), ...
        'hjb', hjb_error < 1e-6, 'kfe', kfe_error < 1e-8, ...
        'capital_market', abs(residuals.capital) < 0.003, ...
        'informal_market', abs(residuals.informal_good) < 2e-4, ...
        'formal_resources', abs(resource) < 0.002, ...
        'government', abs(residuals.government) < 2e-6, ...
        'root_converged', x.root_exitflag > 0 && x.ge_converged, ...
        'increasing_value', shape.increasing_computed_value, ...
        'computed_value_concavity', shape.concave_computed_value_with_tolerance, ...
        'positive_marginal_value', shape.positive_marginal_value, ...
        'nonincreasing_marginal_value', shape.nonincreasing_marginal_value_with_tolerance);
    rows{k} = struct('case_id', case_id, 'mat_sha256', file_sha256(file_path), ...
        'asset_nodes', numel(x.a), 'productivity_nodes', numel(x.z), ...
        'asset_min', min(x.a), 'asset_max', max(x.a), ...
        'phi_I', x.config.phi_I, 'hbar', c.H_bar, ...
        'time_equality', contains(console, 'HEQ_PATCH: 1'), ...
        'r', x.r, 'pI', x.pI, 'capital', x.KD, ...
        'shape', shape, 'residuals', residuals, 'checks', checks, ...
        'passed', all(cell2mat(struct2cell(checks))));
    fprintf('%s: passed=%d, max Vaa=%.3g, max delta Va=%.3g\n', ...
        case_id, rows{k}.passed, shape.maximum_value_curvature, shape.maximum_marginal_value_increase);
end
report = struct('audit_date', char(datetime('today','Format','yyyy-MM-dd')), ...
    'matlab_version', version, 'new_ge_solve', false, ...
    'scope', 'Fresh MATLAB audit of saved GE: computed value shape and equilibrium residuals.', ...
    'continuous_model_global_concavity_proved', false, ...
    'continuous_model_global_existence_proved', false, ...
    'global_precision_certified', false, 'cases', [rows{:}], ...
    'passed', all(cellfun(@(row) row.passed, rows)));
fid = fopen(output_json, 'w', 'n', 'UTF-8');
assert(fid >= 0, 'Cannot write audit output.');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', jsonencode(dense_json_values(report), 'PrettyPrint', true));
assert(report.passed, 'Audit contains failed checks; inspect the retained report.');
end

function value = dense_json_values(value)
% MATLAB preserves sparsity in some scalar reductions; JSON cannot encode it.
if isstruct(value)
    fields = fieldnames(value);
    for k = 1:numel(value)
        for j = 1:numel(fields)
            value(k).(fields{j}) = dense_json_values(value(k).(fields{j}));
        end
    end
elseif issparse(value)
    value = full(value);
end
end

function digest = file_sha256(file_path)
fid = fopen(file_path, 'rb');
assert(fid >= 0);
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid, Inf, '*uint8');
md = java.security.MessageDigest.getInstance('SHA-256');
md.update(bytes);
digest = lower(reshape(dec2hex(typecast(md.digest(), 'uint8'), 2).', 1, []));
end
