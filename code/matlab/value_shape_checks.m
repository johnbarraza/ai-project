function shape = value_shape_checks(assets, value, marginal_value)
% Check concavity of the computed value and its piecewise linear interpolant.
assets = assets(:);
assert(numel(assets) >= 3 && all(isfinite(assets)) && all(diff(assets) > 0));
assert(size(value, 1) == numel(assets) && isequal(size(value), size(marginal_value)));
assert(all(isfinite(value), 'all') && all(isfinite(marginal_value), 'all'));
slopes = diff(value, 1, 1) ./ diff(assets);
curvature = diff(slopes, 1, 1) ./ ((assets(3:end)-assets(1:end-2))/2);
tol_slopes = 1e-8 * max(1, max(abs(slopes), [], 'all'));
tol_marginal = 1e-8 * max(1, max(abs(marginal_value), [], 'all'));
shape = struct( ...
    'minimum_secant_slope', min(slopes, [], 'all'), ...
    'maximum_secant_slope_increase', max(diff(slopes, 1, 1), [], 'all'), ...
    'maximum_value_curvature', max(curvature, [], 'all'), ...
    'value_concavity_violations', nnz(diff(slopes, 1, 1) > tol_slopes), ...
    'secant_slope_tolerance', tol_slopes, ...
    'minimum_marginal_value', min(marginal_value, [], 'all'), ...
    'maximum_marginal_value_increase', max(diff(marginal_value, 1, 1), [], 'all'), ...
    'marginal_value_violations', nnz(diff(marginal_value, 1, 1) > tol_marginal), ...
    'marginal_value_tolerance', tol_marginal);
shape.increasing_computed_value = shape.minimum_secant_slope > 0;
shape.concave_computed_value_with_tolerance = shape.value_concavity_violations == 0;
shape.strictly_negative_computed_curvature = shape.maximum_value_curvature < 0;
shape.positive_marginal_value = shape.minimum_marginal_value > 0;
shape.nonincreasing_marginal_value_with_tolerance = shape.marginal_value_violations == 0;
end
